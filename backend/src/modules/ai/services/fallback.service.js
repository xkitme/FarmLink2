function sourceLines(references) {
  if (!references.length) return ''
  return references.map((r, i) => `${i + 1}. ${r.title}：${r.content}`).join('\n')
}

/** 在内置知识库里按关键词找最贴合的一条（命中关键词数最多者）。 */
function matchTopic(topics, question) {
  let best = null
  let bestScore = 0
  for (const topic of topics) {
    const score = topic.keys.reduce((n, key) => (question.includes(key) ? n + 1 : n), 0)
    if (score > bestScore) {
      best = topic
      bestScore = score
    }
  }
  return best
}

